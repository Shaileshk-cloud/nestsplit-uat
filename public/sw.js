// NestSplit service worker — production only.
// Safety rules:
//   1. NEVER cache "/" or any HTML/navigation document — prevents stale
//      Next.js router payloads ("Router action dispatched before init").
//   2. NEVER cache /_next/ JS chunks at runtime — Next.js content-hashes
//      filenames; stale chunks from old deployments cause runtime errors.
//   3. NEVER cache /api/ routes or Supabase responses — financial data must
//      always be fresh.
//   4. Serve /offline.html from cache only when the user is genuinely offline
//      and requests a navigation (HTML) document.

const CACHE = "nestsplit-shell-v3";
// Only the offline fallback page is pre-cached. Nothing else.
const PRECACHE = ["/offline.html", "/favicon.ico"];

// ── Install: pre-cache the offline shell ──────────────────────────────────
self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)),
  );
  // Activate immediately — don't wait for old tabs to close.
  self.skipWaiting();
});

// ── Activate: purge any caches from previous SW versions ─────────────────
self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))),
      )
      .then(() => self.clients.claim()),
  );
});

// ── Fetch: network-first with offline fallback for navigation only ────────
self.addEventListener("fetch", (event) => {
  const { request } = event;

  // Only handle GET requests from our own origin.
  if (request.method !== "GET") return;

  const url = new URL(request.url);

  // Let the browser handle cross-origin requests (Supabase, Google OAuth,
  // fonts, analytics, etc.) completely unmodified.
  if (url.origin !== self.location.origin) return;

  // ── Block list: never intercept these paths ──────────────────────────
  // Next.js HTML pages (navigation requests) — must always come from network
  // so that new deployments are picked up immediately and the router never
  // receives a stale payload.
  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request).catch(() =>
        // Only when genuinely offline, serve the offline shell.
        caches.match("/offline.html"),
      ),
    );
    return;
  }

  // Next.js JS/CSS chunks — skip caching entirely. Their filenames are
  // content-hashed so there is no benefit to caching, and caching them
  // caused the stale-router problem.
  if (url.pathname.startsWith("/_next/")) return;

  // API routes — never cache.
  if (url.pathname.startsWith("/api/")) return;

  // Supabase paths proxied through our origin — never cache.
  if (url.pathname.startsWith("/rest/") || url.pathname.startsWith("/auth/")) return;

  // Icon routes (generated by Next.js ImageResponse) — let network handle.
  if (
    url.pathname === "/icon" ||
    url.pathname === "/icon2" ||
    url.pathname === "/icon3" ||
    url.pathname === "/apple-icon"
  ) return;

  // ── Safe static assets: serve from cache, update in background ───────
  // This only applies to truly static files in /public (favicon, sw.js
  // itself, offline.html). Everything else falls through to the network.
  event.respondWith(
    caches.match(request).then((cached) => cached ?? fetch(request)),
  );
});
